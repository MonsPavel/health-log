/**
 * TASK-063 §5/§13: чистый конвертер «строки экспорта → CSV» — домен модуля reporting
 * (арх. 02 §3.4): без I/O и node:*, полная детерминированность (тестируемость §19).
 *
 * ФОРМАТ (§4/§5/§13, решение в духе спеки):
 *  - кодировка UTF-8 c BOM `\uFEFF` ПЕРВЫМ символом файла — иначе Excel в ru-локали
 *    открывает UTF-8 как CP1251-кашу (§3/§4); BOM только в начале, к данным не добавляется;
 *  - разделитель `;` — дружелюбие ru-Excel (запятая там — десятичный разделитель, §4);
 *  - заголовок — английские идентификаторы колонок (§16–17: машиночитаемость,
 *    повторный парсинг; второй строка-комментарий НЕ добавляется — только заголовок);
 *  - записи разделяются `\r\n` (RFC 4180), завершающий разделитель после последней
 *    записи не пишется (RFC 4180 допускает оба варианта; отсутствие хвостового CRLF
 *    упрощает roundtrip-парсинг §19);
 *  - экранирование RFC 4180, минимальное: поле оборачивается в кавычки ТОЛЬКО если
 *    содержит `;`, `"`, `\r` или `\n`; внутренние `"` удваиваются (`""`); перенос
 *    строки в заметке сохраняется внутри кавычек (§13);
 *  - поля без значения (pulse не измерен, руки/заметки нет) — пустые ячейки;
 *    irregular — литералы `true`/`false` (§5).
 *
 * ПОРЯДОК СТРОК toCsv НЕ меняет: хронология takenAt asc — забота use case (§13).
 *
 * БЕЗОПАСНОСТЬ (§14, осознанное решение): CSV-инъекция (формулы вида `=cmd()` в
 * заметке) НЕ санитизируется — это данные пользователя для него самого; предупреждение
 * «не открывать чужие CSV без проверки» документируется в README экспорта (TASK-065 —
 * вместе с записью файла на диск).
 *
 * ПРОИЗВОДИТЕЛЬНОСТЬ (§15): сборка через массив + join (конкатенация строк в цикле
 * квадратична); 50k строк ≈ 3 МБ — файл целиком в памяти приемлем (§8).
 */

/** Плоская строка экспорта (§7): форма CSV — всё строково-примитивное, без вложенности. */
export interface ExportRow {
  /** Идентификатор записи (uuid v7 агрегата). */
  readonly id: string;
  /** Идентификатор профиля-владельца (принудительный скоуп, арх. 08 §3). */
  readonly profileId: string;
  /** Момент измерения: ISO 8601 с настенным временем и offset («2026-09-24T08:12:00+03:00», §5) — читаемо человеку и парсится однозначно. */
  readonly datetime: string;
  /** Систолическое АД, мм рт. ст. */
  readonly sys: number;
  /** Диастолическое АД, мм рт. ст. */
  readonly dia: number;
  /** ЧСС, уд/мин; undefined — не измерен (FR-1.1) → пустая ячейка. */
  readonly pulse: number | undefined;
  /** «Неровный пульс» — литерал true/false (§5). */
  readonly irregular: boolean;
  /** Рука измерения; undefined → пустая ячейка. */
  readonly arm: 'left' | 'right' | undefined;
  /** Заметка; undefined → пустая ячейка. Может содержать `;"` и переносы — экранируются (§13). */
  readonly note: string | undefined;
  /** Источник записи: ручной ввод или импорт (агрегат TASK-017). */
  readonly source: 'manual' | 'import';
}

/** Заголовок CSV (§16–17): английские идентификаторы колонок, порядок фиксирован. */
const CSV_HEADER_LINE = 'id;profileId;datetime;sys;dia;pulse;irregular;arm;note;source';

/** BOM UTF-8 (§4/§5): обязателен для Excel в ru-локали, ставится только в начало файла. */
const UTF8_BOM = '\uFEFF';

/** Разделитель записей RFC 4180. */
const RECORD_SEPARATOR = '\r\n';

/** Спецсимволы экранирования (§13): разделитель, кавычка, оба перевода строки. */
const NEEDS_QUOTES = /[";\r\n]/;

/** Экранирует одно поле RFC 4180: кавычки только при спецсимволах, `"` → `""` (§13). */
function csvField(value: string): string {
  return NEEDS_QUOTES.test(value) ? `"${value.replaceAll('"', '""')}"` : value;
}

/** Строка одной записи ExportRow (§5): порядок колонок CSV_HEADER_LINE, опционалы → ''. */
function rowToLine(row: ExportRow): string {
  return [
    row.id,
    row.profileId,
    row.datetime,
    String(row.sys),
    String(row.dia),
    row.pulse === undefined ? '' : String(row.pulse),
    row.irregular ? 'true' : 'false',
    row.arm ?? '',
    row.note ?? '',
    row.source,
  ]
    .map(csvField)
    .join(';');
}

/**
 * Конвертер «все записи → CSV» (§5): BOM + заголовок + записи `\r\n`-разделителем.
 * Чистая функция: вход не мутируется, порядок строк входа сохраняется (asc — use case).
 */
export function toCsv(rows: readonly ExportRow[]): string {
  const lines: string[] = [CSV_HEADER_LINE];
  for (const row of rows) {
    lines.push(rowToLine(row));
  }
  return UTF8_BOM + lines.join(RECORD_SEPARATOR);
}
