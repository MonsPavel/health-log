/**
 * TASK-070 §5/§9: FileOpQueue — сериализация файловых операций данных (копии и
 * будущие экспорты, §9: «FileOpQueue сериализует с экспортом»). Promise-мьютекс:
 * операции стартуют строго по одной в порядке поступления; сбой одной не роняет
 * очередь (следующая выполняется) — финальный результат операции возвращается
 * вызывающему как есть (Result/исключение).
 *
 * Почему не общий workerPool (TASK-066): там CPU-задачи в worker_threads без
 * доступа к БД/ФС userData (§8 пула); копии работают с диском рядом с БД и
 * требуют строгого порядка с будущими экспортами — отдельная очередь в main.
 */
export class FileOpQueue {
  /** Хвост цепочки: всегда выполненный promise (успех или сбой предыдущей операции). */
  private tail: Promise<void> = Promise.resolve();

  /**
   * Ставит операцию в очередь (§9). Возвращает результат/ошибку самой операции;
   * сбой предыдущих операций очередь не прерывает.
   */
  run<T>(operation: () => Promise<T>): Promise<T> {
    const enqueued = this.tail.then(operation, operation);
    // Хвост продолжает цепочку независимо от исхода операции.
    this.tail = enqueued.then(
      () => undefined,
      () => undefined,
    );
    return enqueued;
  }
}
