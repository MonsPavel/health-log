/**
 * TASK-121 §3/§5: порт импорта ключа БД из копии в ЛОКАЛЬНЫЙ vault — минимальная
 * структурная поверхность (прецедент BackupDatabase: application не импортирует
 * чужие модули/адаптеры, арх. 03 §4). Реализация — SafeStorageKeyVault
 * (модуль security) удовлетворяет структурно.
 *
 * Семантика (TASK-121 §3, решение зафиксировано в use case): восстановление
 * заменяет ВСЁ (SRS UC-08) — файл vault.key переписывается обёрткой импортируемого
 * ключа (safeStorage, формат v2 — прецедент generateAndStore TASK-023), сессия
 * vault-а переезжает на импортированный ключ (кэш §13). Режим passphrase прежнего
 * vault-а НЕ переносится («не включено» — перенос vault-сессий/автоблока, §3):
 * импортированный ключ живёт в safeStorage-режиме. Вызывается ТОЛЬКО после
 * успешного открытия подменённой БД ключом копии — сбой импорта не оставляет
 * расхождения «БД одного ключа — vault другого» (откат-страховка при нетронутом
 * vault).
 */
import type { AppError, Result } from '@hl/kernel';

/** Порт vault-а для восстановления (TASK-121 §3). */
export interface RestoreKeyVault {
  /**
   * Импортирует ключ БД (64 hex-символа, 32 байта) в локальный vault: safeStorage-
   * обёртка → запись vault.key (v2, mode='safeStorage') → кэш сессии на импортированном
   * ключе. Нарушение контракта keyHex — TypeError (dev-контракт, прецедент assertKeyHex
   * TASK-022). Ошибки среды — значением Result: VAULT/UNAVAILABLE (нет ОС-хранилища),
   * APP/INTERNAL (сбой записи файла). Property-синтаксис (не method) — функция без
   * this-контекста (моки тестов ссылаются на неё напрямую).
   */
  importKey: (keyHex: string) => Promise<Result<void, AppError>>;
}
